package com.notification.app.ui.designsystem

import androidx.compose.ui.unit.dp

/**
 * Sprint 1 — Application Foundation / Design System.
 *
 * Reusable elevation scale for cards, bars, and sheets, so shadow depth
 * stays consistent across the new screens.
 */
object AppElevation {
    val none = 0.dp
    val low = 2.dp
    val medium = 4.dp
    val high = 8.dp
    val topBar = 2.dp
    val bottomBar = 4.dp
    val floatingCard = 6.dp
}
